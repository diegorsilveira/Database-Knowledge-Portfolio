/*
SGBD: IBM Db2 LUW
CATEGORIA: Monitoramento / Conexões
OBJETIVO: Consultar conexões monitoradas na instância.
IMPACTO: Somente leitura.
*/

SELECT
    APPLICATION_HANDLE,
    APPLICATION_NAME,
    SESSION_AUTH_ID,
    CLIENT_HOSTNAME,
    CLIENT_IPADDR,
    CONNECTION_START_TIME,
    CLIENT_PROTOCOL
FROM TABLE(MON_GET_CONNECTION(NULL, -2)) AS C
ORDER BY CONNECTION_START_TIME;
