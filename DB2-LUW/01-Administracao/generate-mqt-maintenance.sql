/* Db2 LUW | MQT | Gera comandos REFRESH e RUNSTATS; não executa os comandos. */
SELECT 'REFRESH TABLE '||RTRIM(TABSCHEMA)||'.'||RTRIM(TABNAME)||';' AS REFRESH_COMMAND,
 'CALL SYSPROC.ADMIN_CMD(''RUNSTATS ON TABLE '||RTRIM(TABSCHEMA)||'.'||RTRIM(TABNAME)||
 ' WITH DISTRIBUTION AND DETAILED INDEXES ALL'');' AS RUNSTATS_COMMAND
FROM SYSCAT.TABLES WHERE TYPE='S' ORDER BY TABSCHEMA,TABNAME;
